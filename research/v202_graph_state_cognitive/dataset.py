from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import hashlib
import random
import sqlite3

import torch
from torch.utils.data import Dataset

from v200_graph_transformer_cognitive.long_term_memory import (
    RELATION_TO_ID,
    RELATIONS,
)

from .graph_state import (
    ACTION_TO_ID,
    GraphState,
)


@dataclass
class TrajectoryExample:
    current: GraphState
    target_next: GraphState

    source_index: int
    target_index: int
    relation_id: int

    action_id: int


def stable_id(
    concept: str,
    vocab_size: int = 50000,
) -> int:
    value = int.from_bytes(
        hashlib.blake2b(
            concept.encode("utf-8"),
            digest_size=8,
        ).digest(),
        "little",
        signed=False,
    )
    return value % vocab_size


class GraphTrajectoryDataset(Dataset):
    """
    Graph-derived trajectory generator.

    Every example starts from one semantic edge:

        source --relation--> target

    Current state:
        source active

    Target state:
        source + target active
        semantic edge active

    Correct designer action:
        BIND(source, relation, target)

    A small set of negative action examples is generated by using structurally
    valid but incorrect actions as distractors.
    """

    def __init__(
        self,
        db_path: Path,
        *,
        samples: int = 12000,
        seed: int = 202,
        max_neighbors: int = 10,
    ) -> None:
        self.db_path = Path(db_path)
        self.samples = samples
        self.seed = seed
        self.max_neighbors = max_neighbors

        conn = sqlite3.connect(
            str(self.db_path)
        )
        conn.row_factory = sqlite3.Row

        try:
            rows = conn.execute(
                """
                SELECT start, relation, end, weight
                FROM edge
                WHERE relation IN (
                    'IsA',
                    'CapableOf',
                    'HasProperty',
                    'UsedFor',
                    'HasA',
                    'PartOf',
                    'RelatedTo',
                    'SimilarTo',
                    'Antonym',
                    'Causes',
                    'AtLocation'
                )
                ORDER BY RANDOM()
                LIMIT ?
                """,
                (samples,),
            ).fetchall()
        finally:
            conn.close()

        self.rows = [
            (
                row["start"],
                row["relation"],
                row["end"],
                float(row["weight"]),
            )
            for row in rows
            if row["relation"] in RELATION_TO_ID
        ]

        if not self.rows:
            raise RuntimeError(
                "No graph trajectory rows available."
            )

    def __len__(self) -> int:
        return len(self.rows)

    def _build_current_state(
        self,
        source: str,
        target: str,
    ) -> tuple[GraphState, int, int]:
        conn = sqlite3.connect(
            str(self.db_path)
        )
        conn.row_factory = sqlite3.Row

        try:
            neighbors = conn.execute(
                """
                SELECT start, relation, end, weight
                FROM edge
                WHERE start = ?
                ORDER BY weight DESC
                LIMIT ?
                """,
                (
                    source,
                    self.max_neighbors,
                ),
            ).fetchall()
        finally:
            conn.close()

        state = GraphState()

        source_index = state.add_node(
            source,
            role=1,      # SOURCE
            activation=1.0,
        )

        target_index = state.add_node(
            target,
            role=2,      # TARGET
            activation=0.0,
        )

        for row in neighbors:
            end = row["end"]
            relation = row["relation"]

            if relation not in RELATION_TO_ID:
                continue

            neighbor_id = state.add_node(
                end,
                role=0,
                activation=0.20,
            )

            state.add_edge(
                source_index,
                RELATION_TO_ID[relation],
                neighbor_id,
                activation=0.15,
            )

        return (
            state,
            source_index,
            target_index,
        )

    def __getitem__(
        self,
        index: int,
    ) -> TrajectoryExample:
        random.seed(
            self.seed + index
        )

        source, relation, target, _weight = (
            self.rows[index]
        )

        (
            current,
            source_index,
            target_index,
        ) = self._build_current_state(
            source,
            target,
        )

        relation_id = RELATION_TO_ID[
            relation
        ]

        # Target state is generated mechanically from graph semantics.
        target_next = current.clone()

        target_next.nodes[
            target_index
        ].activation = 1.0

        target_next.add_edge(
            source_index,
            relation_id,
            target_index,
            activation=1.0,
        )

        # Preserve one high-salience target edge and a couple of distractors;
        # this lets the transformer learn state change rather than simply
        # copy the source node.
        for edge in target_next.edges:
            if (
                edge.source == source_index
                and edge.target == target_index
                and edge.relation_id == relation_id
            ):
                edge.activation = 1.0

        return TrajectoryExample(
            current=current,
            target_next=target_next,
            source_index=source_index,
            target_index=target_index,
            relation_id=relation_id,
            action_id=ACTION_TO_ID["BIND"],
        )


def collate(
    items: list[TrajectoryExample],
) -> list[TrajectoryExample]:
    return items
